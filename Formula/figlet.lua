  Q = { " # ", "# #", "# #", "###", "  #" }, R = { "## ", "# #", "## ", "# #", "# #" },
  S = { " ##", "#  ", " # ", "  #", "## " }, T = { "###", " # ", " # ", " # ", " # " },
