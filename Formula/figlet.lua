  [" "] = { "   ", "   ", "   ", "   ", "   " },
}
local BLANK = FONT[" "]
local PER_LINE = 9  -- 9 letters of 4 columns fit the 40-column screen

local text = table.concat(arg, " "):upper()
if text == "" then
  print("usage: figlet TEXT")
  return
end

local i = 1
while i <= #text do
  local chunk = text:sub(i, i + PER_LINE - 1)
  for row = 1, 5 do
    local parts = {}
    for c in chunk:gmatch(".") do
      parts[#parts + 1] = (FONT[c] or BLANK)[row] .. " "
    end
    term.print(table.concat(parts), "green")
  end
  i = i + PER_LINE
end
