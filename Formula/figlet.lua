  local mode = full & 255
  local glyphs, rows, code = {}, {}, 32
  for line in body:gmatch("[^\n]+") do
    local row, last = line:match("^(.-)@(@?)$")
    rows[#rows + 1] = row:gsub("%$", HARD)
    if last == "@" then
      local w = 0
      for _, r in ipairs(rows) do if #r > w then w = #r end end
      for i, r in ipairs(rows) do rows[i] = r .. string.rep(" ", w - #r) end
      glyphs[code] = { rows = rows, w = w }
      code, rows = code + 1, {}
    end
  end
  return { height = height, mode = mode, glyphs = glyphs }
end

local function usage(code)
  io.stderr:write(USAGE .. "\n")
  os.exit(code)
end

-- options
local width, align, font, info = 57, "l", "standard", nil
local override, cmdMode = "no", nil   -- override: "no" (the font decides), "yes" (the command line decides), "force"
local words = {}
local i = 1
local noMoreOpts = false
while arg[i] do
  local a = arg[i]
  if noMoreOpts or a:sub(1, 1) ~= "-" or a == "-" then
    words[#words + 1] = a
  elseif a == "--" then
    noMoreOpts = true
  elseif a == "--help" then
    usage(0)
  else
    local j = 2
    while j <= #a do
      local o = a:sub(j, j)
      if o == "c" then align = "c"
      elseif o == "l" then align = "l"
      elseif o == "r" then align = "r"
      elseif o == "x" then align = "l"
      elseif o == "k" then cmdMode, override = SM_KERN, "yes"
      elseif o == "W" then cmdMode, override = 0, "yes"
      elseif o == "S" then cmdMode, override = SM_SMUSH, "force"
      elseif o == "s" then override = "no"
      elseif o == "o" then cmdMode, override = SM_SMUSH, "yes"
      elseif o == "t" or o == "n" or o == "p" or o == "D" or o == "E" or o == "X" or o == "L" or o == "R" or o == "N" then
        -- accepted: no effect here
      elseif o == "v" then
        print(VERSION .. "\n\nFIGlet, along with the various FIGlet fonts and documentation, may be\nfreely copied and distributed.\n\n" ..
              "If you use FIGlet, please send an e-mail message to <info@figlet.org>.\n\nThe latest version of FIGlet is available from the web site,\n\thttp://www.figlet.org/\n\n" .. USAGE)
        return
      elseif o == "f" or o == "w" or o == "I" or o == "d" or o == "m" or o == "C" then
        local val = a:sub(j + 1)
        if val == "" then
          i = i + 1
          val = arg[i]
        end
        if not val then
          io.stderr:write("figlet: option requires an argument -- '" .. o .. "'\n")
          usage(1)
        end
        if o == "f" then font = val:gsub("%.flf$", ""):gsub("^.*/", "")
        elseif o == "w" then
          width = math.floor(tonumber(val) or 57)
          if width < 1 then width = 57 end
        elseif o == "m" then
          local m = math.floor(tonumber(val) or -2)
          if m < -1 then override = "no"
          elseif m == -1 then cmdMode, override = 0, "yes"
          elseif m == 0 then cmdMode, override = SM_KERN, "yes"
          else cmdMode, override = (m & 63) | (m & 128 ~= 0 and SM_SMUSH or SM_SMUSH), "yes" end
        elseif o == "I" then info = tonumber(val) or 0 end
        j = #a
      else
        io.stderr:write("figlet: illegal option -- " .. o .. "\n")
        usage(1)
      end
      j = j + 1
    end
  end
  i = i + 1
end

if info then
  if info == 1 then print("20205")
  elseif info == 2 then print("/usr/share/figlet")
  elseif info == 3 then print("standard")
  elseif info == 4 then print(tostring(width))
  elseif info == 5 then print("flf2 tlf2")
  elseif info == 0 then print(VERSION)
  else print("") end
  return
end

local F = loadFont(font)
if not F then
  io.stderr:write("figlet: " .. font .. ": Unable to open font file\n")
  os.exit(1)
end
local G, H = F.glyphs, F.height
local smushmode = F.mode
if override == "yes" then smushmode = cmdMode
elseif override == "force" then smushmode = cmdMode | F.mode end

-- smush two touching characters like figlet's smushem(); nil when they cannot merge
local HIERARCHY = { { "|" }, { "/", "\\" }, { "[", "]" }, { "{", "}" }, { "(", ")" }, { "<", ">" } }
local CLASS = {}
for k, set in ipairs(HIERARCHY) do for _, c in ipairs(set) do CLASS[c] = k end end
local function smush(l, r, lw, rw)
  if l == " " then return r end
  if r == " " then return l end
  if lw < 2 or rw < 2 then return nil end
  if smushmode & SM_SMUSH == 0 then return nil end
  if smushmode & 63 == 0 then
    if l == HARD then return r end
    if r == HARD then return l end
    return r
  end
  if smushmode & SM_HARDBLANK ~= 0 and l == HARD and r == HARD then return l end
  if l == HARD or r == HARD then return nil end
  if smushmode & SM_EQUAL ~= 0 and l == r then return l end
  if smushmode & SM_LOWLINE ~= 0 then
    if l == "_" and CLASS[r] then return r end
    if r == "_" and CLASS[l] then return l end
  end
  if smushmode & SM_HIERARCHY ~= 0 then
    local a, b = CLASS[l], CLASS[r]
    if a and b and a ~= b then return a > b and l or r end
  end
  if smushmode & SM_PAIR ~= 0 then
    if (l == "[" and r == "]") or (l == "]" and r == "[") or (l == "{" and r == "}") or (l == "}" and r == "{")
       or (l == "(" and r == ")") or (l == ")" and r == "(") then return "|" end
  end
  if smushmode & SM_BIGX ~= 0 then
    if l == "/" and r == "\\" then return "|" end
    if l == "\\" and r == "/" then return "Y" end
    if l == ">" and r == "<" then return "X" end
  end
  return nil
end

-- the input: the words of the command line, or the lines of stdin
local lines = {}
if #words > 0 then
  lines[1] = table.concat(words, " ")
elseif sys.piped then
  local data = io.read("a") or ""
  for l in (data .. (data:sub(-1) == "\n" and "" or "\n")):gmatch("(.-)\n") do lines[#lines + 1] = l end
end

local out = {}
local function emit(rows, len)
  local pad = 0
  if align == "c" then pad = (width - len) // 2
  elseif align == "r" then pad = width - len end
  if pad < 0 then pad = 0 end
  for r = 1, H do
    out[#out + 1] = (string.rep(" ", pad) .. rows[r]):gsub(HARD, " ")
  end
end

-- how many columns the next glyph can slide into the line
local function overlap(cur, curw, prevw, g)
  local amt = g.w
  for r = 1, H do
    local line, row = cur[r], g.rows[r]
    local lb = #line
    while lb > 0 and line:sub(lb, lb) == " " do lb = lb - 1 end
    if lb == 0 then lb = 1 end
    local cb = 1
    while cb <= #row and row:sub(cb, cb) == " " do cb = cb + 1 end
    local a = (cb - 1) + (curw - lb)
    local c1 = line:sub(lb, lb)
    if c1 == "" then c1 = " " end
    local c2 = cb <= #row and row:sub(cb, cb) or nil
    if c1 == " " then a = a + 1
    elseif c2 and smush(c1, c2, prevw, g.w) then a = a + 1 end
    if a < amt then amt = a end
  end
  return amt
end

-- the glyph merged into the line: the new rows and the new width (the overlapped columns are smushed one by one, as figlet does)
local function merge(cur, curw, prevw, g, amt)
  local res = {}
  for r = 1, H do
    local row = g.rows[r]
    if curw == 0 then
      res[r] = row:sub(amt + 1)   -- the first glyph of a line loses the blank columns it could slide over
    else
      local line = cur[r] .. string.rep(" ", math.max(0, curw - #cur[r]))
      local L = {}
      for c = 1, curw do L[c - 1] = line:sub(c, c) end
      for k = 0, amt - 1 do
        local col = math.max(0, curw - amt + k)
        local rc = row:sub(k + 1, k + 1)
        L[col] = smush(L[col] or "", rc, prevw, g.w) or rc
      end
      res[r] = table.concat(L, "", 0, curw - 1) .. row:sub(amt + 1)
    end
  end
  return res, curw + g.w - amt
end

local cur, curw, prevw, inchr, mode
local function clearline()
  cur = {}
  for r = 1, H do cur[r] = "" end
  curw, prevw, inchr = 0, 0, {}
end

-- adds a character to the line; false when it does not fit
local function addchar(c, force)
  local g = G[c]
  if not g then return true end
  local amt = 0
  if smushmode & (SM_KERN | SM_SMUSH) ~= 0 then amt = overlap(cur, curw, prevw, g) end
  if not force and curw + g.w - amt > width - 1 then return false end
  cur, curw = merge(cur, curw, prevw, g, amt)
  prevw = g.w
  inchr[#inchr + 1] = c
  return true
end

local function printline()
  local pad = 0
  if align == "c" then pad = (width - curw) // 2
  elseif align == "r" then pad = width - 1 - curw end
  if pad < 0 then pad = 0 end
  for r = 1, H do
    out[#out + 1] = (string.rep(" ", pad) .. cur[r]):gsub(HARD, " ")
  end
  clearline()
end

-- breaks the line at its last blank: what is before goes out, what is after starts the next line
local function splitline()
  local n = #inchr
  local lastspace, got, i = 0, false, n
  while i >= 1 do
    if not got and inchr[i] == 32 then got, lastspace = true, i end
    if got and inchr[i] ~= 32 then break end
    i = i - 1
  end
  local part1, part2 = {}, {}
  for k = 1, i do part1[#part1 + 1] = inchr[k] end
  for k = lastspace + 1, n do part2[#part2 + 1] = inchr[k] end
  clearline()
  for _, c in ipairs(part1) do addchar(c, true) end
  printline()
  for _, c in ipairs(part2) do addchar(c, true) end
  mode = #part2 > 0 and 1 or 0
end

for _, text in ipairs(lines) do
  clearline()
  mode = 0
  for n = 1, #text do
    local c = text:byte(n)
    if c == 9 then c = 32 end
    while true do
      if addchar(c) then
        if c ~= 32 then mode = mode >= 2 and 3 or 1 else mode = mode > 0 and 2 or 0 end
        break
      elseif curw == 0 then
        addchar(c, true)
        mode = 0
        break
      elseif (c == 32 and mode == 2) or (c ~= 32 and mode >= 2) then
        splitline()
        if c == 32 then break end   -- a blank that ended up at the start of the new line is dropped
      else
        printline()
        mode = 0
        if c == 32 then break end
      end
    end
  end
  printline()
end

for _, l in ipairs(out) do print(l) end
